const MONSTER_COLORS = [0xa, 0x2, 0x8, 0x7, 0x1, 0x5]

function spawnMonster(dir: number) {
    const L = LEVELS[currentLevel]
    const color = MONSTER_COLORS[randint(0, MONSTER_COLORS.length - 1)]
    const map: number[] = []
    for (let i = 0; i < 16; i++) map.push(i)
    map[0xa] = color
    let frames = MONSTER_DRIVE.map(function (f: Image) { return recolor(f, map) })
    if (dir > 0) frames = mirrored(frames)
    const m = sprites.create(frames[0], SpriteKind.Monster)
    m.setFlag(SpriteFlag.GhostThroughWalls, true)
    m.z = 20
    const left = scene.cameraProperty(CameraProperty.Left)
    if (dir < 0) m.left = left + 164
    else m.right = left - 4
    m.bottom = L.roadRow * 16 + 1
    m.vx = dir * randint(150, 190)
    m.lifespan = 3200
    animation.runImageAnimation(m, frames, 70, true)
    sfx(music.zapped)
}

game.onUpdate(function () {
    if (levelBusy || !player) return
    const L = LEVELS[currentLevel]
    if (L.roadTo == 0) return
    const now = game.runtime()
    const col = player.x / 16
    if (col < L.roadFrom - 2 || col > L.roadTo + 2) {
        nextMonster = 0
        return
    }
    if (nextMonster == 0) nextMonster = now + randint(1500, 2500)
    if (!monsterWarned && now > nextMonster - 900) {
        monsterWarned = true
        monsterDir = Math.percentChance(70) ? -1 : 1
        const w = sprites.create(WARNING_SIGN[0], SpriteKind.Warning)
        w.setFlag(SpriteFlag.RelativeToCamera, true)
        w.setPosition(monsterDir < 0 ? 148 : 12, 60)
        w.lifespan = 900
        animation.runImageAnimation(w, WARNING_SIGN, 120, true)
        music.play(music.tonePlayable(196, music.beat(BeatFraction.Quarter)), music.PlaybackMode.InBackground)
    }
    if (now > nextMonster) {
        spawnMonster(monsterDir)
        nextMonster = now + randint(2600, 4500)
        monsterWarned = false
    }
})

sprites.onOverlap(SpriteKind.Player, SpriteKind.Monster, function (p: Sprite, m: Sprite) {
    if (game.runtime() < invulnUntil) return
    player.sayText("Monster!", 800)
    damagePlayer(m.x, 170)
})

sprites.onOverlap(SpriteKind.Enemy, SpriteKind.Monster, function (e: Sprite, m: Sprite) {
    defeatEnemy(e, "Monster!")
})

