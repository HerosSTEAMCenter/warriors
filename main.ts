// Small helpers for storing per-sprite values
function getNum(s: Sprite, key: string): number { const v = s.data[key]; return v ? v : 0 }
function setNum(s: Sprite, key: string, v: number) { s.data[key] = v }
function getFlag(s: Sprite, key: string): boolean { return !!s.data[key] }
function setFlag(s: Sprite, key: string, v: boolean) { s.data[key] = v }
function getStr(s: Sprite, key: string): string { const v = s.data[key]; return v ? v : "" }
function setStr(s: Sprite, key: string, v: string) { s.data[key] = v }

// Restart an animation only when it actually changes.
function setAnim(s: Sprite, key: string, frames: Image[], interval: number, loop: boolean) {
    if (getStr(s, "anim") == key) return
    setStr(s, "anim", key)
    animation.runImageAnimation(s, frames, interval, loop)
}

function sfx(m: music.Melody) {
    music.play(music.melodyPlayable(m), music.PlaybackMode.InBackground)
}

function tileIs(col: number, row: number, t: Image): boolean {
    if (col < 0 || row < 0 || col >= mapCols || row >= mapRows) return false
    return tiles.tileAtLocationEquals(tiles.getTileLocation(col, row), t)
}

function isWallAt(col: number, row: number): boolean {
    if (col < 0 || col >= mapCols) return true
    if (row < 0 || row >= mapRows) return false
    return tiles.tileAtLocationIsWall(tiles.getTileLocation(col, row))
}

function inWater(s: Sprite): boolean {
    const col = Math.floor(s.x / 16)
    const row = Math.floor((s.bottom - 5) / 16)
    return tileIs(col, row, T_WATER_A) || tileIs(col, row, T_WATER_B) || tileIs(col, row, T_DEEP_WATER)
}

function fellOut(s: Sprite): boolean {
    return s.bottom >= mapRows * 16 - 2
}

// Put a sprite so its feet rest on the bottom of the given tile.
function placeOnFloor(s: Sprite, col: number, row: number) {
    s.x = col * 16 + 8
    s.bottom = row * 16 + 16
}

