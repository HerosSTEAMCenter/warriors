function onGround(s: Sprite): boolean {
    return s.isHittingTile(CollisionDirection.Bottom)
}

function tryJump() {
    if (levelBusy || !player || game.runtime() < hurtUntil) return
    if (onGround(player)) {
        player.vy = JUMP_SPEED
        sfx(music.jumpUp)
    }
}

controller.A.onEvent(ControllerButtonEvent.Pressed, tryJump)
controller.up.onEvent(ControllerButtonEvent.Pressed, tryJump)

controller.B.onEvent(ControllerButtonEvent.Pressed, function () {
    const now = game.runtime()
    if (levelBusy || !player || now < attackReady || now < hurtUntil) return
    attackUntil = now + 270
    attackReady = now + 340
    const d = facing > 0 ? 0 : 1
    setStr(player, "anim", "")
    setAnim(player, "attack" + d, FIREHEART.attack[d], 90, false)
    sfx(music.thump)
    for (const e of sprites.allOfKind(SpriteKind.Enemy)) {
        const dx = (e.x - player.x) * facing
        if (dx > -8 && dx < 20 + e.width / 2 && Math.abs(e.bottom - player.bottom) < 8 + e.height / 2) {
            hitEnemy(e)
        }
    }
    for (const m of sprites.allOfKind(SpriteKind.Food)) {
        const dx = (m.x - player.x) * facing
        if (dx > -8 && dx < 24 && Math.abs(m.bottom - player.bottom) < 12) catchPrey(m)
    }
})

function damagePlayer(fromX: number, knock: number) {
    const now = game.runtime()
    if (now < invulnUntil || levelBusy) return
    info.changeLifeBy(-1)
    invulnUntil = now + 1500
    hurtUntil = now + 380
    const away = player.x < fromX ? -1 : 1
    player.vx = away * knock
    player.vy = -130
    scene.cameraShake(3, 250)
    sfx(music.smallCrash)
}

function loseLifeAndRespawn(reason: string) {
    if (levelBusy) return
    info.changeLifeBy(-1)
    player.x = safeX
    player.y = safeY - 2
    player.vx = 0
    player.vy = 0
    invulnUntil = game.runtime() + 1500
    player.sayText(reason, 1200)
    sfx(music.wawawawaa)
}

function catchPrey(m: Sprite) {
    if (m.kind() != SpriteKind.Food) return
    m.setKind(SpriteKind.Fallen)
    m.destroy(effects.hearts, 200)
    info.changeScoreBy(50)
    if (info.life() < 9) info.changeLifeBy(1)
    player.sayText("Fresh-kill!", 800)
    sfx(music.baDing)
}

sprites.onOverlap(SpriteKind.Player, SpriteKind.Food, function (p: Sprite, m: Sprite) {
    catchPrey(m)
})

// Out of lives? StarClan sends Fireheart back to the start of the SAME level
// (with full lives) instead of ending the game.
info.onLifeZero(function () {
    if (levelBusy) return
    levelBusy = true
    control.runInParallel(retryLevel)
})

function retryLevel() {
    player.vx = 0
    sfx(music.wawawawaa)
    pause(600)
    game.splash("Fireheart has fallen...", "StarClan sends you back!")
    info.setLife(5)
    info.setScore(levelStartScore)
    loadLevel(currentLevel)
}

game.onUpdate(function () {
    if (levelBusy || !player) return
    const now = game.runtime()
    const grounded = onGround(player)

    if (now >= hurtUntil) {
        let dir = 0
        if (controller.left.isPressed()) dir -= 1
        if (controller.right.isPressed()) dir += 1
        player.vx = dir * PLAYER_SPEED
        if (dir != 0 && now >= attackUntil) facing = dir
    }
    // keep Fireheart inside the map (the map edge acts like a wall he can get wedged on)
    if (player.left < 1) { player.left = 1; if (player.vx < 0) player.vx = 0 }
    if (player.right > mapCols * 16 - 1) { player.right = mapCols * 16 - 1; if (player.vx > 0) player.vx = 0 }
    if (grounded && !inWater(player)) {
        safeX = player.x
        safeY = player.y
    }

    const d = facing > 0 ? 0 : 1
    if (now < hurtUntil) setAnim(player, "hurt" + d, FIREHEART.hurt[d], 200, false)
    else if (now < attackUntil) { /* attack animation is already playing */ }
    else if (!grounded) setAnim(player, "jump" + d, FIREHEART.jump[d], 200, false)
    else if (player.vx != 0) setAnim(player, "walk" + d, FIREHEART.walk[d], 90, true)
    else setAnim(player, "idle" + d, FIREHEART.idle[d], 320, true)

    player.setFlag(SpriteFlag.Invisible, now < invulnUntil && Math.idiv(now, 90) % 2 == 0)

    if (inWater(player)) loseLifeAndRespawn("Splash! Too deep!")
    else if (fellOut(player)) loseLifeAndRespawn("Ow! The gorge!")

    // the level exit
    const col = Math.floor(player.x / 16)
    const row = Math.floor(player.y / 16)
    if (tileIs(col, row, T_STAR_A) || tileIs(col, row, T_STAR_B)) {
        if (foesLeft <= 0) {
            levelBusy = true
            control.runInParallel(levelComplete)
        } else if (now > lockedMsgAt) {
            lockedMsgAt = now + 2000
            player.sayText("Defeat " + foesLeft + " more!", 1500)
        }
    }
})

function levelComplete() {
    player.vx = 0
    sfx(music.powerUp)
    effects.confetti.startScreenEffect(1500)
    pause(1200)
    effects.confetti.endScreenEffect()
    info.changeScoreBy(500)
    if (currentLevel + 1 < LEVELS.length) {
        game.splash("Level complete!", "ThunderClan cheers you!")
        loadLevel(currentLevel + 1)
    } else {
        game.splash("Tigerstar is defeated!", "ThunderClan is safe.")
        game.showLongText("Bluestar names you Firestar, leader of ThunderClan. StarClan grants you nine lives. The forest is at peace... for now.", DialogLayout.Center)
        game.over(true, effects.confetti)
    }
}

