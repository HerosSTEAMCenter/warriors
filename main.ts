function loadLevel(n: number) {
    levelBusy = true
    currentLevel = n
    const L = LEVELS[n]
    for (const k of [SpriteKind.Enemy, SpriteKind.Food, SpriteKind.Monster, SpriteKind.Fallen, SpriteKind.Warning]) {
        sprites.destroyAllSpritesOfKind(k)
    }
    boss = null
    foesLeft = 0
    nextMonster = 0
    monsterWarned = false

    mapRows = L.map.length
    mapCols = 0
    for (const row of L.map) mapCols = Math.max(mapCols, row.length)

    // A real MakeCode tilemap built from the ASCII map, using our custom tiles.
    const data = control.createBuffer(4 + mapCols * mapRows)
    data.setNumber(NumberFormat.UInt16LE, 0, mapCols)
    data.setNumber(NumberFormat.UInt16LE, 2, mapRows)
    const tileset: Image[] = [TRANSPARENT_TILE, T_WATER_B, T_STAR_B]
    for (let i = 0; i < TILE_CHARS.length; i++) tileset.push(tileForChar(TILE_CHARS.charAt(i)))
    tiles.setCurrentTilemap(tiles.createTilemap(data, image.create(mapCols, mapRows), tileset, TileScale.Sixteen))

    let startCol = 1, startRow = 1
    for (let r = 0; r < mapRows; r++) {
        const row = L.map[r]
        for (let c = 0; c < mapCols; c++) {
            const ch = c < row.length ? row.charAt(c) : "."
            const loc = tiles.getTileLocation(c, r)
            if (TILE_CHARS.indexOf(ch) >= 0) {
                tiles.setTileAt(loc, tileForChar(ch))
                tiles.setWallAt(loc, WALL_CHARS.indexOf(ch) >= 0)
            } else if (ch == "@") {
                startCol = c; startRow = r
            } else if (ch == "m") {
                spawnMouse(c, r)
            } else if (ch >= "1" && ch <= "5") {
                spawnCat(ch.charCodeAt(0) - 49, c, r)
            }
        }
    }

    buildBackground(L.theme)

    if (!player) {
        player = sprites.create(FIREHEART.idle[0][0], SpriteKind.Player)
        player.ay = GRAVITY
        player.z = 10
        scene.cameraFollowSprite(player)
    }
    placeOnFloor(player, startCol, startRow)
    player.vx = 0
    player.vy = 0
    facing = 1
    safeX = player.x
    safeY = player.y
    setStr(player, "anim", "")
    attackUntil = 0
    hurtUntil = 0
    invulnUntil = 0
    levelStartScore = info.score()

    game.showLongText(L.name + "\n\n" + L.story, DialogLayout.Center)
    levelBusy = false
}

function spawnCat(typeIndex: number, col: number, row: number) {
    const t = CAT_TYPES[typeIndex]
    const e = sprites.create(t.skin.idle[1][0], SpriteKind.Enemy)
    e.scale = t.scale
    e.ay = GRAVITY
    placeOnFloor(e, col, row)
    setNum(e, "type", typeIndex)
    setNum(e, "hp", t.hp)
    setNum(e, "dir", -1)
    setNum(e, "hurtUntil", 0)
    setNum(e, "atkUntil", 0)
    setNum(e, "atkReady", 0)
    setNum(e, "hitAt", 0)
    setFlag(e, "spotted", false)
    setFlag(e, "dead", false)
    foesLeft++
    if (t.boss && typeIndex == 4) boss = e
    if (t.boss && !boss) boss = e
}

