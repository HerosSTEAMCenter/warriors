function level(name: string, story: string, theme: number, map: string[], roadFrom: number, roadTo: number, roadRow: number): Level {
    const l = new Level()
    l.name = name; l.story = story; l.theme = theme; l.map = map
    l.roadFrom = roadFrom; l.roadTo = roadTo; l.roadRow = roadRow
    return l
}

