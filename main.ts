const TILE_CHARS = "GDHRr=#KkB|^f~w*"
const WALL_CHARS = "GDHRr=#KkB"

function tileForChar(ch: string): Image {
    switch (ch) {
        case "G": return T_GRASS
        case "D": return T_DIRT
        case "H": return T_HEATHER
        case "R": return T_ROCK_TOP
        case "r": return T_ROCK
        case "=": return T_ROAD_TOP
        case "#": return T_ROAD
        case "K": return T_MARSH_TOP
        case "k": return T_MUD
        case "B": return T_BRAMBLE
        case "|": return T_TRUNK
        case "^": return T_LEAVES
        case "f": return T_FERN
        case "~": return T_WATER_A
        case "w": return T_DEEP_WATER
        case "*": return T_STAR_A
    }
    return TRANSPARENT_TILE
}

