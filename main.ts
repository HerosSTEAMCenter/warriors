function hitEnemy(e: Sprite) {
    const now = game.runtime()
    if (now < getNum(e, "hurtUntil")) return
    const hp = getNum(e, "hp") - 1
    setNum(e, "hp", hp)
    setNum(e, "hurtUntil", now + 350)
    setNum(e, "atkUntil", 0)
    setNum(e, "dir", -facing)
    const t = CAT_TYPES[getNum(e, "type")]
    e.vx = facing * (t.scale > 1 ? 60 : 100)
    e.vy = -90
    if (hp <= 0) defeatEnemy(e, "")
    else sfx(music.knock)
}

function defeatEnemy(e: Sprite, message: string) {
    if (getFlag(e, "dead")) return
    setFlag(e, "dead", true)
    const t = CAT_TYPES[getNum(e, "type")]
    foesLeft--
    info.changeScoreBy(t.points)
    e.setKind(SpriteKind.Fallen)
    e.setFlag(SpriteFlag.GhostThroughWalls, false)
    if (message != "") e.sayText(message, 800)
    else if (t.boss) e.sayText("Nooo!", 800)
    const d = getNum(e, "dir") > 0 ? 0 : 1
    animation.runImageAnimation(e, t.skin.hurt[d], 200, false)
    e.destroy(effects.disintegrate, 700)
    sfx(t.boss ? music.bigCrash : music.zapped)
    if (foesLeft == 0) player.sayText("Now to the StarClan star!", 1500)
}

function groundAhead(e: Sprite, dir: number): boolean {
    const col = Math.floor((e.x + dir * (e.width / 2 + 2)) / 16)
    const row = Math.floor((e.bottom + 4) / 16)
    return isWallAt(col, row)
}

function wallAhead(e: Sprite, dir: number): boolean {
    return dir > 0 ? e.isHittingTile(CollisionDirection.Right) : e.isHittingTile(CollisionDirection.Left)
}

game.onUpdate(function () {
    if (levelBusy || !player) return
    const now = game.runtime()
    for (const e of sprites.allOfKind(SpriteKind.Enemy)) {
        const t = CAT_TYPES[getNum(e, "type")]
        let dir = getNum(e, "dir")
        const grounded = onGround(e)
        const hurt = now < getNum(e, "hurtUntil")
        const attacking = now < getNum(e, "atkUntil")
        const dx = player.x - e.x
        const dy = player.bottom - e.bottom
        const sees = Math.abs(dx) < t.sight && Math.abs(dy) < 40 * t.scale && now >= invulnUntil - 1000

        if (inWater(e)) { defeatEnemy(e, "Swept away!"); continue }
        if (fellOut(e)) { defeatEnemy(e, "Aaah!"); continue }

        // the claw strike lands part-way through the attack animation
        const hitAt = getNum(e, "hitAt")
        if (hitAt > 0 && now >= hitAt) {
            setNum(e, "hitAt", 0)
            const reach = (player.x - e.x) * dir
            if (!hurt && reach > -6 && reach < e.width / 2 + 16 && Math.abs(dy) < 12 * t.scale) {
                damagePlayer(e.x, t.scale > 1 ? 160 : 110)
            }
        }

        if (hurt) {
            e.vx = e.vx * 0.9
        } else if (attacking) {
            e.vx = 0
        } else if (grounded) {
            if (sees) {
                if (!getFlag(e, "spotted")) {
                    setFlag(e, "spotted", true)
                    e.sayText(t.boss ? "Fireheart! You'll pay!" : t.clan + "!", 900)
                }
                dir = dx > 0 ? 1 : -1
                const close = Math.abs(dx) < e.width / 2 + 14 && Math.abs(dy) < 12 * t.scale
                if (close && now >= getNum(e, "atkReady")) {
                    setNum(e, "atkUntil", now + 300)
                    setNum(e, "atkReady", now + t.cooldown)
                    setNum(e, "hitAt", now + 150)
                    const d0 = dir > 0 ? 0 : 1
                    setStr(e, "anim", "")
                    setAnim(e, "attack" + d0, t.skin.attack[d0], 100, false)
                    e.vx = 0
                } else if (close) {
                    e.vx = 0
                } else if (!groundAhead(e, dir)) {
                    e.vx = 0  // don't chase off a ledge
                } else {
                    e.vx = dir * t.chaseSpeed
                    // pounce!
                    const far = Math.abs(dx)
                    if (far > 30 && far < 80 && Math.percentChance(t.boss ? 3 : 1)) {
                        e.vy = t.boss ? -200 : -170
                        e.vx = dir * t.chaseSpeed * 1.6
                    }
                }
            } else {
                if (wallAhead(e, dir) || !groundAhead(e, dir)) dir = -dir
                e.vx = dir * t.speed
            }
        }
        setNum(e, "dir", dir)

        const d = dir > 0 ? 0 : 1
        if (hurt) setAnim(e, "hurt" + d, t.skin.hurt[d], 200, false)
        else if (attacking) { /* attack animation already running */ }
        else if (!grounded) setAnim(e, "jump" + d, t.skin.jump[d], 200, false)
        else if (e.vx != 0) setAnim(e, "walk" + d, t.skin.walk[d], Math.abs(e.vx) > 45 ? 90 : 140, true)
        else setAnim(e, "idle" + d, t.skin.idle[d], 320, true)
    }

    // prey: wander, and flee from Fireheart
    for (const m of sprites.allOfKind(SpriteKind.Food)) {
        let dir = getNum(m, "dir")
        const dx = m.x - player.x
        let speed = 20
        if (Math.abs(dx) < 50 && Math.abs(m.y - player.y) < 30) {
            dir = dx > 0 ? 1 : -1
            speed = 55
        } else if (now > getNum(m, "turnAt")) {
            setNum(m, "turnAt", now + 800 + randint(0, 1500))
            dir = Math.percentChance(50) ? 1 : -1
        }
        if (wallAhead(m, dir) || !groundAhead(m, dir)) {
            dir = -dir
        }
        if (inWater(m) || fellOut(m)) { m.destroy(); continue }
        m.vx = onGround(m) ? dir * speed : m.vx
        setNum(m, "dir", dir)
        setAnim(m, "run" + dir, MOUSE_FRAMES[dir > 0 ? 0 : 1], speed > 30 ? 80 : 160, true)
    }
})

