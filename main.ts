// -----------------------------------------------------------------------------
//  Coats: every cat is the same template recoloured, so the cast shares one
//  art style. Template colours are Fireheart's: 4 fur, e stripes, b spots,
//  d light fur, 7 eyes.
// -----------------------------------------------------------------------------
class CatSkin {
    // index 0 = facing right, 1 = facing left
    idle: Image[][]
    walk: Image[][]
    jump: Image[][]
    attack: Image[][]
    hurt: Image[][]
}

function recolor(src: Image, map: number[]): Image {
    const out = src.clone()
    for (let x = 0; x < out.width; x++) {
        for (let y = 0; y < out.height; y++) {
            const c = out.getPixel(x, y)
            if (c != 0) out.setPixel(x, y, map[c])
        }
    }
    return out
}

function mirrored(frames: Image[]): Image[] {
    return frames.map(function (f: Image) {
        const m = f.clone()
        m.flipX()
        return m
    })
}

function bothWays(frames: Image[], map: number[]): Image[][] {
    const right = frames.map(function (f: Image) { return recolor(f, map) })
    return [right, mirrored(right)]
}

function makeSkin(fur: number, stripes: number, spots: number, light: number, eyes: number): CatSkin {
    const map: number[] = []
    for (let i = 0; i < 16; i++) map.push(i)
    map[0x4] = fur
    map[0xe] = stripes
    map[0xb] = spots
    map[0xd] = light
    map[0x7] = eyes
    const s = new CatSkin()
    s.idle = bothWays(CAT_IDLE, map)
    s.walk = bothWays(CAT_WALK, map)
    s.jump = bothWays(CAT_JUMP, map)
    s.attack = bothWays(CAT_ATTACK, map)
    s.hurt = bothWays(CAT_HURT, map)
    return s
}

